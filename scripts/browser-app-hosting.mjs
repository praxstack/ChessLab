// Hosting files for the browser-only app (npm run build:app), which Cloudflare Pages serves.
// The plugin writes _headers, the web app manifest and the app icons into web/dist-app only.
// The server build (npm run build) gets none of them; Express sets its own headers.
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

// Icons that ship only with the browser app. Rendered once from web/public/favicon.svg.
const ICON_DIR = fileURLToPath(new URL('../web/app-public/', import.meta.url));
const ICONS = ['icon-192.png', 'icon-512.png', 'apple-touch-icon.png'];

// Public services the browser app talks to: endgame tablebase, Lichess, and Claude with the learner's own key.
export const APP_CONNECT = ['https://tablebase.lichess.ovh', 'https://lichess.org', 'https://api.anthropic.com'];

/** The coach Worker's origin from VITE_COACH_URL, or null when unset. Anything but https (or http on localhost) stops the build. */
export function coachOrigin(value) {
  if (!value || !value.trim()) return null;
  let url;
  try { url = new URL(value.trim()); } catch { throw new Error(`VITE_COACH_URL must be a full URL such as https://coach.example.workers.dev, not "${value}".`); }
  const local = url.protocol === 'http:' && ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
  if (url.protocol !== 'https:' && !local) throw new Error(`VITE_COACH_URL must use https, not "${value}".`);
  return url.origin;
}

/** The content-security policy for every page and file of the browser app. */
export function appCsp({coachUrl} = {}) {
  const coach = coachOrigin(coachUrl);
  return [
    "default-src 'self'",
    // wasm-unsafe-eval lets the Stockfish engine compile its WebAssembly; it does not allow eval().
    "script-src 'self' 'wasm-unsafe-eval'",
    "style-src 'self'",
    "img-src 'self' data: blob:",
    "font-src 'self'",
    `connect-src ${["'self'", ...APP_CONNECT, ...(coach ? [coach] : [])].join(' ')}`,
    // The engine runs in a Web Worker loaded from this site.
    "worker-src 'self'",
    "manifest-src 'self'",
    "frame-src 'none'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    'upgrade-insecure-requests',
  ].join('; ');
}

/** The security headers every file of the app carries. The /betapp gate on askthemove.online
 *  reads the same map from headers.json, because Cloudflare does not apply _headers to Function responses. */
export function appHeaderMap({coachUrl} = {}) {
  return {
    'Content-Security-Policy': appCsp({coachUrl}),
    'X-Content-Type-Options': 'nosniff',
    'Referrer-Policy': 'same-origin',
    'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()',
    'X-Frame-Options': 'DENY',
    'Cross-Origin-Opener-Policy': 'same-origin',
    'Cross-Origin-Resource-Policy': 'same-origin',
    'Strict-Transport-Security': 'max-age=31536000',
    // Search engines should list askthemove.online, not the app or its pages.dev address.
    'X-Robots-Tag': 'noindex',
  };
}

/** The Cloudflare Pages _headers file. */
export function appHeaders({coachUrl} = {}) {
  return [
    '# Generated by scripts/browser-app-hosting.mjs during npm run build:app. Edit there, not here.',
    '/*',
    ...Object.entries(appHeaderMap({coachUrl})).map(([name, value]) => `  ${name}: ${value}`),
    '',
    // Vite puts a content hash in every file name under /assets, so a new build never reuses a cached file.
    '/assets/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
    // The engine files keep their names between builds, so they are cached for 30 days, not forever.
    '/engine/*',
    '  Cache-Control: public, max-age=2592000',
    '',
  ].join('\n');
}

/** The web app manifest, so the app can be added to a home screen. */
export function appManifest(base = '/') {
  return {
    name: 'AskTheMove',
    short_name: 'AskTheMove',
    description: 'Play a chess coach, review your decisions, and explore another line.',
    start_url: base,
    scope: base,
    display: 'standalone',
    background_color: '#fbfaf4',
    theme_color: '#fbfaf4',
    icons: [
      {src: `${base}favicon.svg`, sizes: 'any', type: 'image/svg+xml'},
      {src: `${base}icon-192.png`, sizes: '192x192', type: 'image/png'},
      {src: `${base}icon-512.png`, sizes: '512x512', type: 'image/png'},
    ],
  };
}

/** Vite plugin: active only when VITE_BACKEND=local, so the server build stays as it was. */
export function browserAppHosting() {
  let env = {};
  let base = '/';
  const active = () => env.VITE_BACKEND === 'local';
  return {
    name: 'askthemove-browser-app-hosting',
    apply: 'build',
    // config.env is what the app sees as import.meta.env, so the CSP names the same coach URL the app calls.
    configResolved(config) { env = config.env; base = config.base; },
    transformIndexHtml() {
      if (!active()) return;
      return [
        {tag: 'link', attrs: {rel: 'manifest', href: `${base}manifest.webmanifest`, crossorigin: 'use-credentials'}, injectTo: 'head'},
        {tag: 'link', attrs: {rel: 'apple-touch-icon', href: `${base}apple-touch-icon.png`}, injectTo: 'head'},
      ];
    },
    generateBundle() {
      if (!active()) return;
      this.emitFile({type: 'asset', fileName: '_headers', source: appHeaders({coachUrl: env.VITE_COACH_URL})});
      this.emitFile({type: 'asset', fileName: 'headers.json', source: `${JSON.stringify(appHeaderMap({coachUrl: env.VITE_COACH_URL}), null, 2)}\n`});
      this.emitFile({type: 'asset', fileName: 'manifest.webmanifest', source: `${JSON.stringify(appManifest(base), null, 2)}\n`});
      for (const icon of ICONS) this.emitFile({type: 'asset', fileName: icon, source: readFileSync(ICON_DIR + icon)});
    },
  };
}
